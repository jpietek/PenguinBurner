#!/usr/bin/env python3
"""Generate native overlay metadata from its Python owners. Use --check in CI."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from overlay import metrics, style  # noqa: E402

NATIVE = ROOT / "overlay/native/latency_layer/src"


def strings(values) -> str:
    return ", ".join(json.dumps(value) for value in values)


def generated_files() -> dict[Path, str]:
    prefix = "// Generated by scripts/generate_overlay_contract.py; do not edit.\n#pragma once\n"
    visuals = prefix + "#include <array>\nnamespace pblayer {\n"
    for name, value in vars(style).items():
        if not name.isupper():
            continue
        if isinstance(value, tuple):
            visuals += f"inline constexpr std::array<double, {len(value)}> k{name} = {{{', '.join(map(str, value))}}};\n"
        else:
            visuals += f"inline constexpr double k{name} = {float(value)};\n"
    visuals += "}\n"
    data = prefix + "// Include after latency_layer_internal.h.\nnamespace pblayer {\n"
    data += f"inline constexpr std::array<const char*, {len(metrics.OVERLAY_ITEM_IDS)}> kOverlayItemOrder = {{{strings(metrics.OVERLAY_ITEM_IDS)}}};\n"
    data += f"inline const std::vector<std::string> kOverlayDefaultItems = {{{strings(metrics.DEFAULT_ENABLED_OVERLAY_ITEM_IDS)}}};\n"
    groups = [group for group in metrics.OVERLAY_ROW_GROUPS if any(item not in metrics.OVERLAY_NON_TEXT_ITEM_IDS for item in group)]
    data += f"inline const std::array<std::vector<const char*>, {len(groups)}> kOverlayRowGroups = {{{{\n"
    data += "".join("    {" + strings(group) + "},\n" for group in groups) + "}};\n"
    data += "struct OverlayHudRow { OverlayRowKind kind; const char* label; std::vector<const char*> items; };\n"
    data += "inline const std::vector<OverlayHudRow> kOverlayHudRows = {\n"
    for kind, label, items in metrics.OVERLAY_HUD_ROWS:
        data += f"    {{OverlayRowKind::{kind.title()}, {json.dumps(label)}, {{{strings(items)}}}}},\n"
    data += "};\n"
    data += "struct OverlayMetricSpec { const char* id; const char* unit; const char* table_label; const char* hud_label; std::string OverlayGpuState::*field; const char* missing; const char* table_missing; bool missing_unit; };\n"
    data += "inline const OverlayMetricSpec kOverlayMetrics[] = {\n"
    # Plain sensor fields use one formatter. Frame statistics, identities and
    # compound measurements keep their explicit calculations in each language.
    for key, spec in metrics.METRICS.items():
        if not spec.sensor:
            continue
        data += f"    {{{strings((key, spec.unit, spec.table_label, spec.hud_label))}, &OverlayGpuState::{spec.telemetry_key}, {strings((spec.missing, spec.table_missing))}, {str(spec.missing_unit).lower()}}},\n"
    data += "};\n}\n"
    return {NATIVE / "overlay_style.h": visuals, NATIVE / "overlay_metrics.h": data}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale overlay contract: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
