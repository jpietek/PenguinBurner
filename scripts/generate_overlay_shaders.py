#!/usr/bin/env python3
"""Compile the overlay's shaders into a committed SPIR-V header.

The Vulkan layer needs SPIR-V at runtime, but making every distribution
packager install glslang to build PenguinBurner would be a poor trade for two
shaders that change about once a year. So the SPIR-V is generated here, on a
developer machine that has glslangValidator, and committed as a C header the
layer includes.

Run from the repository root:

    python scripts/generate_overlay_shaders.py

``--check`` verifies the committed header still matches its sources, which is
what the test suite uses.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile


SHADER_DIR = Path("overlay/native/latency_layer/shaders")
HEADER_PATH = Path("overlay/native/latency_layer/src/overlay_shaders.h")
SHADERS = (("overlay.vert", "kOverlayVertexSpirv"), ("overlay.frag", "kOverlayFragmentSpirv"))

SPIRV_MAGIC = 0x07230203


def compile_spirv(source: Path, compiler: str) -> list[int]:
    """Compile one shader and return its SPIR-V as 32-bit words."""
    with tempfile.TemporaryDirectory() as work:
        output = Path(work) / "shader.spv"
        subprocess.run(
            [compiler, "-V", "--target-env", "vulkan1.0", str(source), "-o", str(output)],
            check=True,
            capture_output=True,
            text=True,
        )
        blob = output.read_bytes()
    if len(blob) % 4:
        raise ValueError(f"{source}: SPIR-V is not a whole number of words")
    words = list(struct.unpack(f"<{len(blob) // 4}I", blob))
    if not words or words[0] != SPIRV_MAGIC:
        raise ValueError(f"{source}: output does not start with the SPIR-V magic word")
    return words


def render_header(compiler: str, shader_dir: Path) -> str:
    lines = [
        "// Generated by scripts/generate_overlay_shaders.py -- do not edit by hand.",
        "//",
        "// SPIR-V for the overlay's blended-quad pipeline, compiled from the GLSL in",
        "// overlay/native/latency_layer/shaders/. Committed so building the layer",
        "// needs only a C++ compiler.",
        "#ifndef PENGUINBURNER_OVERLAY_SHADERS_H",
        "#define PENGUINBURNER_OVERLAY_SHADERS_H",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace pblayer {",
    ]
    for name, symbol in SHADERS:
        words = compile_spirv(shader_dir / name, compiler)
        lines += ["", f"// {name}", f"constexpr std::array<uint32_t, {len(words)}> {symbol} = {{"]
        for index in range(0, len(words), 6):
            row = ", ".join(f"0x{word:08x}" for word in words[index : index + 6])
            lines.append(f"    {row},")
        lines.append("};")
    lines += ["", "}  // namespace pblayer", "", "#endif  // PENGUINBURNER_OVERLAY_SHADERS_H", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when stale")
    parser.add_argument("--output", type=Path, default=HEADER_PATH)
    parser.add_argument("--shader-dir", type=Path, default=SHADER_DIR)
    args = parser.parse_args(argv)

    compiler = shutil.which("glslangValidator") or shutil.which("glslang")
    if compiler is None:
        print("glslangValidator not found; install glslang to regenerate", file=sys.stderr)
        return 2

    rendered = render_header(compiler, args.shader_dir)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != rendered:
            print(
                f"{args.output} is stale; re-run scripts/generate_overlay_shaders.py",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
